const q = (s) => JSON.stringify(String(s));
function writeConfig() {
  const s = state.settings;
  let t = `# Generated by the console. Edit through the UI.\ndry_run = ${!!s.dryRun}\nchain_id = ${BSC.chainId}\ndb_path = ${q(F.db)}\n\n`;
  t += `[rpc]\nhttp = [${q(s.rpcHttp)}]\nws = [${s.rpcWs ? q(s.rpcWs) : ''}]\n\n[executor]\nkey_file = ${q(F.key)}\n\n`;
  t += `[budget]\nusd_micros = ${Math.round(s.budgetUsd * 1e6)}\nmin_price_micros = 100000000\nmax_price_micros = 5000000000\nprice_pair = ${q(BSC.pricePair)}\nprice_stable = ${q(BSC.usdt)}\n\n`;
  t += `[[channels]]\nname = "public"\nkind = "public"\nurl = ${q(s.rpcHttp)}\n`;
  for (const k of state.tasks.filter((k) => !k.archived)) {
    t += `\n[[tasks]]\ntask_id = ${q(k.taskId)}\nexecutor_contract = ${q(k.executorContract)}\nowner = ${q(k.owner)}\ntoken_in = ${q(k.token)}\ntoken_out = ${q(BSC.wbnb)}\nfactory = ${q(BSC.factory)}\npair_init_code_hash = ${q(BSC.initCodeHash)}\n`;
    t += `amount_in = ${q('0x' + BigInt(k.amount).toString(16))}\nmin_out = ${q('0x' + BigInt(k.minOut).toString(16))}\nmode = ${q(k.mode)}\ngas_limit = ${GAS_LIMIT}\ngas_price_wei = ${k.gasPriceWei}\nchannels = ["public"]\n`;
    t += `max_attempts = ${k.maxAttempts}\nwindow_blocks = ${k.windowBlocks}\nrequire_sim_ok = ${k.mode !== 'pre_armed_spray'}\nspray_per_block = ${k.mode === 'pre_armed_spray' ? 1 : 0}\n`;
    if (k.probe) t += `arm_probe = { to = ${q(k.probe.to)}, data = ${q(k.probe.selector)}, min_value = ${q('0x' + BigInt(k.probe.min).toString(16))} }\n`;
  }
  fs.writeFileSync(F.toml, t, { mode: 0o600 });
}
