// ---------------------------------------------------------------- helpers
const run = (cmd, args, opts = {}) => new Promise((res) => execFile(cmd, args, { timeout: 120000, maxBuffer: 8 << 20, env: { ...process.env, NODE_USE_ENV_PROXY: '1' }, ...opts }, (err, stdout, stderr) => res({ err, stdout, stderr })));
async function shooter(...args) {
  if (!BIN) throw new Error('未找到 shooter 可执行文件，请先在 shooter/ 目录执行 cargo build --release');
  const r = await run(BIN, ['--config', F.toml, ...args]);
  const line = r.stdout.trim().split('\n').filter((l) => l.startsWith('{')).pop();
  if (r.err && !line) throw new Error((r.stderr.trim().split('\n').pop() || r.err.message).replace(/^Error: /, ''));
  return line ? JSON.parse(line) : { text: r.stdout };
}
async function baw(...args) {
  const r = await run('baw', [...args, '--json']);
  let j; try { j = JSON.parse(r.stdout); } catch { throw new Error('钱包 CLI 无响应：' + (r.stderr || r.err?.message || '').slice(0, 200)); }
  if (!j.success) throw new Error(j.error?.message || '钱包拒绝了请求');
  return j.data;
}
async function rpc(method, params = []) {
  const r = await fetch(state.settings.rpcHttp, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }), signal: AbortSignal.timeout(8000) });
  const j = await r.json();
  if (j.error) throw Object.assign(new Error(j.error.message), { rpc: true });
  return j.result;
}
const pad = (a) => a.toLowerCase().replace(/^0x/, '').padStart(64, '0');
const call = (to, data) => rpc('eth_call', [{ to, data }, 'latest']);
const big = (h) => (h && h !== '0x' ? BigInt(h) : 0n);
const isAddr = (a) => /^0x[0-9a-fA-F]{40}$/.test(a || '');
function str(hex) { // ABI string, or bytes32-style symbol
  try {
    const b = Buffer.from(hex.slice(2), 'hex');
    if (b.length >= 96) { const len = Number(BigInt('0x' + b.subarray(32, 64).toString('hex'))); return b.subarray(64, 64 + len).toString('utf8'); }
    return b.toString('utf8').replace(/\0/g, '');
  } catch { return ''; }
}

let walletCache = null;
async function wallet() {
  if (walletCache) return walletCache;
  const d = await baw('wallet', 'address');
  const a = d.addresses?.find((x) => String(x.binanceChainId) === '56')?.address;
  if (!a) throw new Error('钱包未返回 BSC 地址');
  return (walletCache = a);
}
let execCache = null;
async function executor() {
  if (!fs.existsSync(F.key)) return null;
  return (execCache ??= (await shooter('address')).address);
}
async function bnbPrice() {
  const [t0, r] = await Promise.all([call(BSC.pricePair, '0x0dfe1681'), call(BSC.pricePair, '0x0902f1ac')]);
  const r0 = BigInt('0x' + r.slice(2, 66)), r1 = BigInt('0x' + r.slice(66, 130));
  const usdtFirst = ('0x' + t0.slice(26)).toLowerCase() === BSC.usdt.toLowerCase();
  return Number(((usdtFirst ? r0 : r1) * 1000000n) / (usdtFirst ? r1 : r0)) / 1e6;
}

function probeOf(p) {
  if (!p || !p.to) return null;
  if (!isAddr(p.to) || !/^0x[0-9a-f]{8}$/i.test(p.selector || '') || !/^\d+$/.test(String(p.min)) || BigInt(p.min) <= 0n) throw new Error('自动预埋条件不完整：需要合约地址、进度读数和阈值');
  return { to: p.to, selector: p.selector.toLowerCase(), min: BigInt(p.min).toString() };
}

let deploying = false, adoptChecked = 0;
// Picks up an executor contract that was deployed but not recorded (e.g. the console was closed mid-deploy).
async function adoptDeployed() {
  if (Date.now() - adoptChecked < 30000) return; adoptChecked = Date.now();
  const a = await executor().catch(() => null); if (!a) return;
  if (Number(await rpc('eth_getTransactionCount', [a, 'latest']).catch(() => '0x0')) === 0) return;
  const r = await shooter('deploy', '--artifact', ARTIFACT).catch(() => null);
  if (r?.reused && isAddr(r.address)) { state.executorContract = r.address; state.deploy = r; save(); }
}

// ---------------------------------------------------------------- daemon
let daemon = null; const logs = [];
function startDaemon() {
  if (daemon) return;
  // detached: false keeps it in our process group, so launchd stopping the console also stops it.
  daemon = spawn(BIN, ['--config', F.toml, 'run'], { env: { ...process.env, RUST_LOG: 'info' }, detached: false });
  const push = (buf) => buf.toString().split('\n').filter(Boolean).forEach((l) => { logs.push(l); if (logs.length > 300) logs.shift(); });
  daemon.stdout.on('data', push); daemon.stderr.on('data', push);
  daemon.on('exit', (code) => { logs.push(JSON.stringify({ level: 'INFO', fields: { message: `守护进程已退出 (${code})` } })); daemon = null; });
}
function stopDaemon() { if (daemon) daemon.kill('SIGINT'); }
// Never leave a live daemon behind: give it a moment to exit cleanly on SIGINT, then force it.
function shutdown() {
  if (!daemon) process.exit(0);
  const d = daemon; d.once('exit', () => process.exit(0)); stopDaemon();
  setTimeout(() => { try { d.kill('SIGKILL'); } catch {} process.exit(0); }, 8000).unref();
}
for (const sig of ['SIGINT', 'SIGTERM', 'SIGHUP']) process.on(sig, shutdown);

