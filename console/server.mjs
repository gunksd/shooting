const GET_TASK = '15a29035', CANCEL_TASK = 'ee8ca3b5';

http.createServer(async (req, res) => {
  const url = new URL(req.url, 'http://x');
  const host = req.headers.host || '';
  if (!/^(127\.0\.0\.1|localhost):\d+$/.test(host)) { res.writeHead(403).end(); return; } // DNS-rebinding guard
  if (url.pathname.startsWith('/api/')) {
    const h = api[`${req.method} ${url.pathname}`];
    const send = (code, body) => { res.writeHead(code, { 'content-type': 'application/json' }); res.end(JSON.stringify(body)); };
    if (!h) return send(404, { error: 'not found' });
    if (req.method === 'POST' && req.headers['x-console'] !== '1') return send(403, { error: 'forbidden' }); // blocks cross-site form posts
    let body = ''; for await (const c of req) body += c;
    try { send(200, await h(body ? JSON.parse(body) : {})); } catch (e) { send(400, { error: e.message }); }
    return;
  }
  res.writeHead(200, { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store' });
  fs.createReadStream(path.join(HERE, 'index.html')).pipe(res);
}).listen(PORT, '127.0.0.1', () => console.log(`控制台已启动: http://127.0.0.1:${PORT}`));
